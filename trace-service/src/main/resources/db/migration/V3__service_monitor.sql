create table service_instance (
 instance_id varchar(100) primary key, service_name varchar(100) not null,
 base_url varchar(500) not null, enabled boolean not null default true,
 state varchar(20) not null default 'UNKNOWN', failures integer not null default 0,
 successes integer not null default 0, last_checked timestamp with time zone,
 reason varchar(100), policy_version varchar(20) not null default '1'
);
create table service_state_history (
 id bigint generated by default as identity primary key, instance_id varchar(100) not null,
 previous_state varchar(20) not null, state varchar(20) not null,
 reason varchar(100) not null, observed_at timestamp with time zone not null
);
create table operational_incident (
 incident_id varchar(36) primary key, instance_id varchar(100) not null,
 opened_at timestamp with time zone not null, recovered_at timestamp with time zone,
 acknowledged_at timestamp with time zone, acknowledged_by varchar(100),
 state varchar(20) not null
);
create index incident_instance_idx on operational_incident(instance_id,state);
create table operational_audit (
 event_id varchar(36) primary key, actor varchar(100) not null, action varchar(50) not null,
 target_id varchar(100) not null, created_at timestamp with time zone not null
);
