create table if not exists auth_user (
    id bigint generated by default as identity primary key,
    user_id varchar(50) not null unique,
    user_name varchar(100) not null,
    password_hash varchar(200) not null,
    status varchar(20) not null,
    role varchar(20) not null default 'USER'
);

create table if not exists refresh_family (
    family_id varchar(36) primary key,
    user_id varchar(50) not null references auth_user(user_id),
    expires_at timestamp with time zone not null,
    revoked_at timestamp with time zone
);
create table if not exists refresh_session (
    token_hash char(64) primary key,
    family_id varchar(36) not null references refresh_family(family_id),
    expires_at timestamp with time zone not null,
    used_at timestamp with time zone,
    revoked_at timestamp with time zone
);
create index if not exists refresh_session_family_idx on refresh_session(family_id);
create table if not exists auth_security_event (
    event_id varchar(36) primary key,
    user_id varchar(50),
    family_id varchar(36),
    event_type varchar(40) not null,
    created_at timestamp with time zone not null
);
